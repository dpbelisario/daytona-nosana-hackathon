// Copies ../sandbox/{bootstrap.sh,edge.mjs,inject.mjs} into lib/runtime-files.ts
// so the factory (deployed from factory/ only) can upload them to sandboxes.
// Run after editing sandbox/: npm run sync-runtime
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const files = ["bootstrap.sh", "edge.mjs", "inject.mjs", "hosts.mjs"]
const body = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(root, "..", "sandbox", f), "utf8"))},`).join("\n")
writeFileSync(
  join(root, "lib", "runtime-files.ts"),
  `// GENERATED by scripts/sync-runtime.mjs from ../sandbox. Do not edit.\nexport const RUNTIME_FILES: Record<string, string> = {\n${body}\n}\n`,
)
console.log(`synced ${files.join(", ")}`)
